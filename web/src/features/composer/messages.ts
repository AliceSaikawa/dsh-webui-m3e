/** The composer texts for one language; plain functions take this as their last optional parameter. */
export type ComposerMessages = Translation<typeof composerMessages.ja>

/**
 * The composer texts for the language in use now. Non-React code calls this
 * when it produces a text (a thrown error, a stored status, a snackbar) so the
 * text follows a language change without a reload.
 */
export function composerText(): ComposerMessages {
  return messagesOf(composerMessages, currentLocale())
}
