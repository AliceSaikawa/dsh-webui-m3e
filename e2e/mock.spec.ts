test('10a 開発mockのPWAメタデータとSW未登録', async ({ page }) => {
  await visit(page)
  await expect(page.locator('link[rel="manifest"]')).toHaveAttribute('href', /\/m3e\/manifest\.webmanifest/)
  const response = await page.request.get('/m3e/manifest.webmanifest')
  expect(response.ok()).toBeTruthy()
  const manifest = await response.json()
  expect(manifest.scope).toBe('/m3e/')
  expect(manifest.start_url).toBe('/m3e/')
  expect(manifest.display).toBe('standalone')
  expect(await page.evaluate(async () => (await navigator.serviceWorker.getRegistrations()).length)).toBe(0)
  await expect(page.locator('meta[name="apple-mobile-web-app-capable"]')).toHaveAttribute('content', 'yes')
})
