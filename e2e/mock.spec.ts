test('02b チャットとトレースの往復で各スクロール位置・検索条件を保持', async ({ page }) => {
  await visit(page, '/s/chat-long')
  const chat = page.locator('.chat-scroll')
  await expect.poll(() => chat.evaluate(node => node.scrollHeight - node.clientHeight)).toBeGreaterThan(500)
  await expect.poll(() => chat.evaluate(node => node.scrollHeight - node.clientHeight - node.scrollTop)).toBeLessThan(3)
  const chatBottom = await chat.evaluate(node => node.scrollTop)
  await chat.hover()
  await page.mouse.wheel(0, -400)
  await expect.poll(() => chat.evaluate(node => node.scrollTop)).toBeLessThan(chatBottom - 200)
  const chatPosition = await chat.evaluate(node => node.scrollTop)
  await shot(page, '02-chat-scrolled')
  await page.getByRole('tab', { name: 'トレース', exact: true }).click()
  const trace = page.locator('.trace-scroll')
  await expect.poll(() => trace.evaluate(node => node.scrollHeight - node.clientHeight)).toBeGreaterThan(500)
  await expect(page.getByLabel('メッセージ入力欄')).toHaveCount(0)
  const traceStart = await trace.evaluate(node => node.scrollTop)
  await trace.hover()
  await page.mouse.wheel(0, -400)
  await expect.poll(() => trace.evaluate(node => node.scrollTop)).toBeLessThan(traceStart - 200)
  const tracePosition = await trace.evaluate(node => node.scrollTop)
  await shot(page, '04-trace-scrolled')
  await page.getByRole('tab', { name: 'チャット', exact: true }).click()
  await expect.poll(() => chat.evaluate(node => node.scrollTop)).toBeCloseTo(chatPosition, 0)
  await page.getByRole('tab', { name: 'トレース', exact: true }).click()
  await expect.poll(() => trace.evaluate(node => node.scrollTop)).toBeCloseTo(tracePosition, 0)
  await page.getByLabel('記録を検索').fill('確認')
  await page.getByRole('tab', { name: 'チャット', exact: true }).click()
  await page.getByRole('tab', { name: 'トレース', exact: true }).click()
  await expect(page.getByLabel('記録を検索')).toHaveValue('確認')
})

